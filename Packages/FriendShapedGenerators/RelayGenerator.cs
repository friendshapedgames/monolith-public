using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace FriendShapedGenerators;

/// <summary>
///     [Relay&lt;IProvider&gt;] on a partial class implements IProvider by forwarding every get-only property
///     to the nearest IProvider ancestor (via one shared CachedAncestor).
/// </summary>
[Generator]
public sealed class RelayGenerator : IIncrementalGenerator
{
    // `1 = one type parameter; metadata names of generic types carry their arity
    private const string AttributeName = "SecretPlanGodot.Core.RelayAttribute`1";

    private static readonly DiagnosticDescriptor _unsupportedType = new(
        "FSRELAY001",
        "Unsupported [Relay] target",
        "[Relay] does not support nested or generic classes ('{0}')",
        "FriendShapedGenerators",
        DiagnosticSeverity.Error,
        true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // RelayAttribute itself is ordinary code in SecretPlanGodot; it's found by name.
        // Only classes carrying [Relay] are ever looked at; Roslyn does the filtering cheaply
        var outputs = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => Build(ctx))
            .Where(static x => x != null);

        context.RegisterSourceOutput(outputs, static (spc, x) =>
        {
            if (x!.Error != null)
            {
                spc.ReportDiagnostic(Diagnostic.Create(_unsupportedType, x.Error.ToLocation(), x.Error.TypeName));
                return;
            }

            spc.AddSource(x.HintName!, x.Source!);
        });
    }

    // Returns plain strings (not symbols) so the incremental cache can compare by value
    private static RelayOutput? Build(GeneratorAttributeSyntaxContext ctx)
    {
        var type = (INamedTypeSymbol)ctx.TargetSymbol;
        // Attributes only holds the [Relay<T>] matches, and AllowMultiple is off, so [0] is the only one
        if (ctx.Attributes[0].AttributeClass?.TypeArguments.FirstOrDefault() is not INamedTypeSymbol provider)
        {
            return null;
        }

        if (type.ContainingType != null || type.IsGenericType)
        {
            // Points at the class name rather than the whole declaration
            var location = ((ClassDeclarationSyntax)ctx.TargetNode).Identifier.GetLocation();
            var error = new RelayError(
                location.SourceTree?.FilePath ?? string.Empty,
                location.SourceSpan,
                location.GetLineSpan().Span,
                type.ToDisplayString());
            return new RelayOutput(null, null, error);
        }

        var fq = SymbolDisplayFormat.FullyQualifiedFormat;
        var providerName = provider.ToDisplayString(fq);

        // Every get-only property on the interface and its bases, e.g. CoreState + WorldState
        var properties = provider.AllInterfaces.Add(provider)
            .SelectMany(i => i.GetMembers().OfType<IPropertySymbol>())
            .Where(p => p.GetMethod != null && p.SetMethod == null)
            // Skip anything the class (or a base class) already implements itself (e.g. World.WorldState)
            .Where(p => !DeclaresProperty(type, p.Name))
            .ToList();

        var stringBuilder = new StringBuilder();
        stringBuilder.AppendLine(
            "// <auto-generated/>");
        stringBuilder.AppendLine(
            "#nullable enable");
        if (!type.ContainingNamespace.IsGlobalNamespace)
        {
            stringBuilder.AppendLine(
                $"namespace {type.ContainingNamespace.ToDisplayString()};");
        }

        stringBuilder.AppendLine();
        stringBuilder.AppendLine(
            $"partial class {type.Name} : {providerName}");
        stringBuilder.AppendLine(
            "{");
        stringBuilder.AppendLine(
            "    // One cached climb shared by every relayed property");
        stringBuilder.AppendLine(
            $"    private readonly global::SecretPlanGodot.Core.CachedAncestor<{providerName}> __relay = new();");
        foreach (var p in properties)
        {
            var t = p.Type.ToDisplayString(fq);
            stringBuilder.AppendLine();
            stringBuilder.AppendLine(
                $"    public {t} {p.Name} =>");
            stringBuilder.AppendLine(
                $"        __relay.GetOrNull(this)?.{p.Name} ?? global::SecretPlanGodot.Core.RelayFallback.Create<{t}>(this);");
        }

        stringBuilder.AppendLine("}");

        return new RelayOutput($"{type.ToDisplayString()}.Relay.g.cs", stringBuilder.ToString(), null);
    }

    private static bool DeclaresProperty(INamedTypeSymbol type, string name)
    {
        for (var current = type; current != null; current = current.BaseType)
        {
            if (current.GetMembers(name).Any(m => m is IPropertySymbol))
            {
                return true;
            }
        }

        return false;
    }

    // Plain values instead of a Location: a Location holds its syntax tree, which changes on every edit and
    // would defeat the incremental cache. The Location is rebuilt in the sink.
    private sealed record RelayError(string FilePath, TextSpan SourceSpan, LinePositionSpan LineSpan, string TypeName)
    {
        public Location ToLocation()
        {
            return Location.Create(FilePath, SourceSpan, LineSpan);
        }
    }

    private sealed record RelayOutput(string? HintName, string? Source, RelayError? Error);
}